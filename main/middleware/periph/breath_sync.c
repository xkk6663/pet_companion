uint8_t breath_phase(uint64_t utc_us)
{
	uint64_t p;

	/* 早于锚点的时刻钳到锚点：真实设备上不会发生（epoch 之后才可能开机）。
	 * 锚点为 0 时这段被条件编译掉，否则编译器会警告“无符号数恒不小于 0”。 */
#if BREATH_ANCHOR_UTC_US != 0
	if (utc_us < (uint64_t)BREATH_ANCHOR_UTC_US) {
		utc_us = (uint64_t)BREATH_ANCHOR_UTC_US;
	}
#endif

	p = (utc_us - (uint64_t)BREATH_ANCHOR_UTC_US) % BREATH_PERIOD_US;

	/* 把 [0, P) 均匀压成 [0, 256)，整除取整 = 零阶保持，最大相位误差 1/512 周期 */
	return (uint8_t)((p * BREATH_LUT_SIZE) / BREATH_PERIOD_US);
}

uint8_t breath_envelope(uint64_t utc_us)
{
	return breath_lut[breath_phase(utc_us)];
}

uint8_t breath_lut_lookup(uint8_t phase)
{
	return breath_lut[phase % BREATH_LUT_SIZE];
}

uint32_t breath_lut_checksum(void)
{
	return BREATH_LUT_CHECKSUM;
}

/* --- 通道层：同一套亮度包络，铺到 n 个通道上 ------------------------------
 * 同步的是“亮度标量”，不是“灯”：单色 LED 只取 n=1，RGB 取 n=3，灯带逐像素调。
 * 所有通道乘同一个 level，所以色相不变、只改明暗——这是“不同灯型也能同相”的前提。 */

void breath_channels(uint64_t utc_us, const uint8_t *base, uint8_t n, uint8_t gain_pct,
		     uint8_t *out)
{
	uint32_t level = breath_envelope(utc_us);
	uint8_t i;

	if (n > BREATH_MAX_CHANNELS) {
		n = BREATH_MAX_CHANNELS;   /* 防呆：传错通道数不要写越界 */
	}
	if (gain_pct > 100u) {
		gain_pct = 100u;           /* gain 是标定值，不是用户可拧的旋钮 */
	}

	/* 先用 32 位乘完再除：255 * 100 会超 uint8，提前截断就会出现“暗部永远是 0” */
	level = (level * gain_pct) / 100u;

	for (i = 0; i < n; i++) {
		out[i] = (uint8_t)(((uint32_t)base[i] * level) / BREATH_LEVEL_MAX);
	}
}

void breath_frame(uint64_t utc_us, const struct breath_rgb *base, uint8_t gain_pct,
		  struct breath_rgb *out)
{
	uint8_t b[3];
	uint8_t ch[3];

	b[0] = base->r;
	b[1] = base->g;
	b[2] = base->b;

	breath_channels(utc_us, b, 3u, gain_pct, ch);

	out->r = ch[0];
	out->g = ch[1];
	out->b = ch[2];
}

uint8_t breath_binary(uint64_t utc_us)
{
	/* 阈值固定 128：开关灯与 PWM 灯在同一毫秒翻转，节拍严格同相 */
	return (breath_envelope(utc_us) >= BREATH_BINARY_THRESHOLD) ? 1u : 0u;
}

uint32_t breath_duty(uint8_t level, uint8_t bits)
{
	uint32_t max;

	if (bits < 8u) {
		bits = 8u;
	}
	if (bits > 16u) {
		bits = 16u;
	}

	max = (1u << bits) - 1u;                     /* 8 位 → 255，16 位 → 65535 */
	return ((uint32_t)level * max) / BREATH_LEVEL_MAX;
}

uint8_t breath_pixel_phase(uint64_t utc_us, uint16_t index, uint8_t step)
{
	uint32_t off = (uint32_t)index * (uint32_t)step;

	return (uint8_t)((breath_phase(utc_us) + off) & 0xFFu);
}

int32_t breath_source_uncertainty_us(uint8_t source)
{
	/* 这是“这口时间本身有多准”，不是“放了多久变多差”（后者由漂移项算）。
	 * 数字来源：各授时方式的公开指标，取保守值。 */
	switch (source) {
	case BREATH_SRC_NETWORK:
		return 25000;      /* SNTP over WiFi：1~30 ms 是常见水平 */
	case BREATH_SRC_GNSS:
		return 1;          /* GPS/北斗 PPS：亚微秒级，按 1 us 记 */
	case BREATH_SRC_LONGWAVE:
		return 10000;      /* BPC/JJY/DCF77：常态 5~20 ms */
	case BREATH_SRC_RTC:
		return 2000;       /* DS3231 一次设定：设定误差 ~2 ms，此后靠 ±2 ppm 走 */
	case BREATH_SRC_LOCAL_LINK:
		return 10000;      /* BLE/ESP-NOW/UART/CAN 广播：协议栈 + 排队 ~10 ms */
	case BREATH_SRC_MANUAL:
		return 200000;     /* 人按秒表/点 App：200 ms 已经算很准了 */
	case BREATH_SRC_NONE:
	default:
		return 1000000;    /* 什么都没说：按“不可信”处理 */
	}
}

int64_t breath_phase_error_us(uint64_t a_utc_us, uint64_t b_utc_us)
{
	const int64_t half = (int64_t)(BREATH_PERIOD_US / 2);
	int64_t d;

	/* 各自先落进 [0, P)，再取环上有符号差：绕周期的两个时刻要能算出“差得很小” */
	d = (int64_t)((a_utc_us % BREATH_PERIOD_US) - (b_utc_us % BREATH_PERIOD_US));

	if (d > half) {
		d -= (int64_t)BREATH_PERIOD_US;
	} else if (d < -half) {
		d += (int64_t)BREATH_PERIOD_US;
	}

	return d;
}

