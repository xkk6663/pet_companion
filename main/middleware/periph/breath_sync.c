void breath_clock_init(struct breath_clock *c, int64_t mono_us, int64_t utc_us)
{
	c->utc_anchor_us = utc_us;
	c->mono_anchor_us = mono_us;
	c->rate_ppm = 0;
	c->slew_err_us = 0;
	c->slew_start_mono_us = mono_us;
	c->slew_span_us = 0;
	c->prev_mono_us = mono_us;
	c->prev_utc_us = utc_us;
	c->last_obs_mono_us = mono_us;
	c->uncertainty_us = 25000;
	c->source = BREATH_SRC_NETWORK;
	c->has_prev = 1;
	c->rate_valid = 0;
	c->synced = 1;
}

void breath_clock_init_freerun(struct breath_clock *c, int64_t mono_us)
{
	/* 上电时刻当作 epoch 0：单机呼吸照常，多机只要同时上电就天然同相。
	 * synced = 0 是关键——亮度守卫会把这盏灯压成半亮，提示“我还没对上表”。 */
	breath_clock_init(c, mono_us, 0);
	c->synced = 0;
	c->source = BREATH_SRC_NONE;
	c->uncertainty_us = breath_source_uncertainty_us(BREATH_SRC_NONE);
}

int64_t breath_clock_now_us(const struct breath_clock *c, int64_t mono_us)
{
	int64_t dt = mono_us - c->mono_anchor_us;
	int64_t base = c->utc_anchor_us + dt;

	/* 频率校正：dt 最长按「一年」估，dt*ppm 仍在 int64 内
	 * (3.15e13 us × 100 ppm = 3.15e15，离 9.2e18 差三个数量级) */
	if (c->rate_ppm != 0) {
		base += (dt * (int64_t)c->rate_ppm) / 1000000;
	}

	/* 缓释项：误差按单调时间的比例注入，到 slew_span 结束正好注入完 */
	if (c->slew_span_us > 0) {
		int64_t elapsed = mono_us - c->slew_start_mono_us;

		if (elapsed > c->slew_span_us) {
			elapsed = c->slew_span_us;
		}
		if (elapsed > 0) {
			base += (c->slew_err_us * elapsed) / c->slew_span_us;
		}
	}

	return base;
}

/* 把「已经走过的缓释份额」固化进锚点，然后清空缓释状态。
 * 这样后续的 now() 仍然连续，而且新样本算出的误差不会重复计算已抵消的部分。 */
static void breath_slew_bake(struct breath_clock *c, int64_t mono_us)
{
	int64_t elapsed;
	int64_t done;

	if (c->slew_span_us <= 0) {
		return;
	}

	elapsed = mono_us - c->slew_start_mono_us;
	if (elapsed < 0) {
		elapsed = 0;
	}
	if (elapsed > c->slew_span_us) {
		elapsed = c->slew_span_us;
	}

	done = (c->slew_err_us * elapsed) / c->slew_span_us;
	c->utc_anchor_us += done;

	c->slew_err_us = 0;
	c->slew_span_us = 0;
	c->slew_start_mono_us = mono_us;
}

/* 改斜率时保持「此刻的估计值不变」：否则一改 rate 相位就跳一下，
 * 前面辛苦做的缓释全白费。 */
static void breath_clock_set_rate(struct breath_clock *c, int64_t mono_us, int32_t ppm)
{
	int64_t before = breath_clock_now_us(c, mono_us);

	c->rate_ppm = ppm;
	c->utc_anchor_us += before - breath_clock_now_us(c, mono_us);
}

int breath_clock_observe(struct breath_clock *c, int64_t mono_us, int64_t utc_us)
{
	/* 不带来源的调用：按“一般授时 25 ms”记。量产代码请用 observe_src。 */
	return breath_clock_observe_src(c, mono_us, utc_us, BREATH_SRC_MANUAL, 25000);
}

int breath_clock_observe_src(struct breath_clock *c, int64_t mono_us, int64_t utc_us,
			     uint8_t source, int32_t uncertainty_us)
{
	int64_t err;
	int64_t span_ahead;
	int32_t ppm;

	/* 先把缓释的那部分结清，后面的误差计算才是“剩余真实误差” */
	breath_slew_bake(c, mono_us);

	/* --- 频率学习（可选但重要）：两次远隔的样本之差就是石英漂移 ---
	 * 10 ms 的 SNTP 噪声在 10 min 窗口上是 16 ppm，在 1 h 窗口上是 2.8 ppm，
	 * 所以这里只收「间隔 ≥ 10 min」的样本：
	 *   第一次学到就信它（否则 EMA 会把真值稀释成 1/8，要 8 个样本才爬到位），
	 *   之后再用 1/8 的 EMA 慢慢挪，避免被单次噪声带跑。 */
	if (c->has_prev) {
		int64_t d_mono = mono_us - c->prev_mono_us;

		if (d_mono >= BREATH_RATE_MIN_SPAN_US) {
			int64_t d_utc = utc_us - c->prev_utc_us;
			int64_t skew_us = d_utc - d_mono;

			ppm = (int32_t)((skew_us * 1000000) / d_mono);
			if (ppm > BREATH_RATE_PPM_LIMIT) {
				ppm = BREATH_RATE_PPM_LIMIT;
			} else if (ppm < -BREATH_RATE_PPM_LIMIT) {
				ppm = -BREATH_RATE_PPM_LIMIT;
			}

			if (!c->rate_valid) {
				breath_clock_set_rate(c, mono_us, ppm);
				c->rate_valid = 1;
			} else {
				breath_clock_set_rate(c, mono_us,
						      (int32_t)(((int64_t)c->rate_ppm * 7 + ppm) / 8));
			}
		}
	}

	c->prev_mono_us = mono_us;
	c->prev_utc_us = utc_us;
	c->has_prev = 1;

	/* 记下“这口时间是谁给的、有多准、什么时候给的”
	 * —— 误差预算全靠这三个字段，没有它们就没法回答“现在还算不算同步”。 */
	c->source = source;
	c->uncertainty_us = (uncertainty_us > 0) ? uncertainty_us
						 : breath_source_uncertainty_us(source);
	c->last_obs_mono_us = mono_us;

	err = utc_us - breath_clock_now_us(c, mono_us);

	/* 25 ms 以内：小于一帧（40 ms），改锚点等于什么都没发生 */
	if (err >= -BREATH_SYNC_SMALL_US && err <= BREATH_SYNC_SMALL_US) {
		c->utc_anchor_us += err;
		c->synced = 1;
		return BREATH_SYNC_ABSORBED;
	}

	/* 1 s 以内：按 ≤0.5% 的速率缓释。1 s 的误差 → 200 s 走完，
	 * 期间呼吸速度只快/慢 0.5%，肉眼看不出来，但相位不会被“拨跳”。 */
	if (err >= -BREATH_SYNC_BIG_US && err <= BREATH_SYNC_BIG_US) {
		span_ahead = (err < 0 ? -err : err) * 1000000 / BREATH_SLEW_PPM;

		if (span_ahead < BREATH_SLEW_MIN_SPAN_US) {
			span_ahead = BREATH_SLEW_MIN_SPAN_US;
		}
		if (span_ahead > BREATH_SLEW_MAX_SPAN_US) {
			span_ahead = BREATH_SLEW_MAX_SPAN_US;
		}

		c->slew_err_us = err;
		c->slew_start_mono_us = mono_us;
		c->slew_span_us = span_ahead;
		c->synced = 1;
		return BREATH_SYNC_SLEWING;
	}

	/* 大偏差：首次同步、或者断电三天后重连。这时候“对”比“平滑”重要。 */
	c->utc_anchor_us += err;
	c->slew_err_us = 0;
	c->slew_span_us = 0;
	c->synced = 1;
	return BREATH_SYNC_STEPPED;
}

void breath_clock_set_calib(struct breath_clock *c, int64_t mono_us, int32_t ppm)
{
	if (ppm > BREATH_RATE_PPM_LIMIT) {
		ppm = BREATH_RATE_PPM_LIMIT;
	} else if (ppm < -BREATH_RATE_PPM_LIMIT) {
		ppm = -BREATH_RATE_PPM_LIMIT;
	}

	breath_clock_set_rate(c, mono_us, ppm);
	c->rate_valid = 1;      /* 标定值也当“已知斜率”，后续实测会 EMA 覆盖它 */
}

int64_t breath_clock_error_budget_us(const struct breath_clock *c, int64_t mono_us)
{
	int64_t age;
	int64_t drift_ppm;
	int64_t budget;

	if (!c->synced) {
		return INT64_MAX;
	}

	age = mono_us - c->last_obs_mono_us;
	if (age < 0) {
		age = 0;
	}

	/* 没标定过就按最坏 50 ppm 估；标定过就按实测/标定的 |rate| 估 */
	drift_ppm = c->rate_valid
		     ? (c->rate_ppm < 0 ? -(int64_t)c->rate_ppm : (int64_t)c->rate_ppm)
		     : (int64_t)BREATH_DRIFT_DEFAULT_PPM;

	budget = (int64_t)c->uncertainty_us;          /* 这口时间本身就有的误差 */
	budget += (age * drift_ppm) / 1000000;        /* 放了多久，漂了多少 */

	/* 还在缓释的话，未吸收的那部分也算进预算（它此刻确实偏着） */
	if (c->slew_span_us > 0) {
		int64_t elapsed = mono_us - c->slew_start_mono_us;
		int64_t left;
		int64_t rem;

		if (elapsed < 0) {
			elapsed = 0;
		}
		if (elapsed > c->slew_span_us) {
			elapsed = c->slew_span_us;
		}

		left = c->slew_span_us - elapsed;
		rem = (c->slew_err_us * left) / c->slew_span_us;
		budget += (rem < 0 ? -rem : rem);
	}

	return budget;
}

uint8_t breath_clock_level(const struct breath_clock *c, int64_t mono_us)
{
	int64_t e = breath_clock_error_budget_us(c, mono_us);

	if (e == INT64_MAX) {
		return 0;
	}
	if (e <= BREATH_LEVEL_STRICT_US) {
		return 3;
	}
	if (e <= BREATH_LEVEL_OK_US) {
		return 2;
	}
	if (e <= BREATH_LEVEL_WEAK_US) {
		return 1;
	}
	return 0;
}

uint8_t breath_gain_guard(uint8_t gain_pct, uint8_t level)
{
	/* 未同步不是“藏起来”，而是“诚实地告诉看灯的人”：半亮 = 我还没对上表。 */
	if (level == 0) {
		return (uint8_t)(gain_pct / 2u);
	}
	return gain_pct;
}

void breath_clock_save_state(const struct breath_clock *c, int64_t mono_us,
			     struct breath_clock_save *out)
{
	out->magic = 0x42524854u;                 /* "BRHT" */
	out->utc_us = breath_clock_now_us(c, mono_us);
	out->mono_us = mono_us;
	out->rate_ppm = c->rate_ppm;
	out->source = c->source;
	out->reserved[0] = 0;
	out->reserved[1] = 0;
	out->reserved[2] = 0;
}

int breath_clock_restore(struct breath_clock *c, const struct breath_clock_save *in,
			 int64_t mono_us)
{
	if (in->magic != 0x42524854u) {
		return -1;
	}

	/* 前提：单调时钟跨重启连续（RTC 备份域 / 电池供电不中断）。
	 * 不满足这个前提时不要调用——那样会把“关机时长”当成 0，误差被低估。 */
	breath_clock_init(c, in->mono_us, in->utc_us);
	breath_clock_set_calib(c, mono_us, in->rate_ppm);
	c->source = (uint8_t)in->source;
	c->synced = 1;
	c->last_obs_mono_us = mono_us;

	/* 从“保存”到“本次上电”这段是时间空白，长度不可知。
	 * 用放大 10 倍的不确定度把它显式计入预算，逼调用方尽快再授一次时。 */
	c->uncertainty_us = breath_source_uncertainty_us(in->source) * 10;

	return 0;
}

int32_t breath_clock_rate_ppm(const struct breath_clock *c)
{
	return c->rate_ppm;
}

/* ④ ----------------------------------------------------------------- 自检 */

int breath_selftest(void)
{
	uint32_t h = 0x811C9DC5u;
	uint32_t i;

	for (i = 0; i < BREATH_LUT_SIZE; i++) {
		h ^= breath_lut[i];
		h *= 0x01000193u;
	}
	if (h != BREATH_LUT_CHECKSUM) {
		return -1;
	}

	for (i = 0; i < breath_vector_count; i++) {
		if (breath_phase(breath_vectors[i].utc_us) != breath_vectors[i].phase) {
			return -2;
		}
		if (breath_envelope(breath_vectors[i].utc_us) != breath_vectors[i].level) {
			return -3;
		}
	}

	return 0;
}
