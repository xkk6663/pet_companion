/*
 * breath_sync.c —— 「按绝对时间同步呼吸」的芯片无关实现
 *
 * 四层，同步只发生在前两层：
 *   L2 波形层   phase → LUT → level(0..255)     ← 一致性全靠这里
 *   L2 通道层   level × base[n] × gain → n 个通道 ← n=1 单色 / 3 RGB / N 灯带
 *   L3 时钟层   单调时钟 + 校时（step/slew/漂移学习）
 *   ④ 自检：表校验和 + 向量比对
 *
 * 文件结构：
 *   ① 生成区段：LUT(256) + 校验和 + 验收向量   ← 由 tools/gen_breath_table.py 维护
 *   ② 纯函数层：相位 → 包络 → 通道值
 *   ③ 时钟层：授时可插拔（SNTP/RTC/BLE/GPIO 秒脉冲…）+ 误差预算
 *   ④ 自检
 *
 * 这一层不出现 k_uptime / k_sleep / GPIO / led_strip。
 * 换到 STM32、nRF、Linux、PC 上，这个文件可以原样编译（只要求 C99）。
 */

